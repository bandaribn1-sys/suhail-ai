import { NextResponse } from 'next/server';

export async function POST(req: Request) {
  try {
    const { brand, niche, tone, audience, agent = 'strategist' } = await req.json();

    await new Promise((resolve) => setTimeout(resolve, 1000));

    let result = '';

    if (agent === 'strategist') {
      result = `📊 الخطة التسويقية الشاملة (من وإلى) - ${brand}
      
1️⃣ تحليل السوق والتموضع:
- المجال: ${niche}
- الجمهور المستهدف: ${audience}
- نبرة الصوت: ${tone}

2️⃣ الأهداف الرئيسية (أول 90 يوم):
- بناء الوعي بالعلامة التجارية في السوق السعودي والخليجي.
- تحويل المتابعين إلى عملاء فعليين عبر قمع مبيعات واضح.

3️⃣ القنوات المقترحة وتوزيع الجهد:
- تيك توك وإنستغرام (60%): للوصول السريع وبناء الثقة.
- سناب شات (30%): للاستهداف الجغرافي والمبيعات المباشرة.
- واتساب للأعمال (10%): لإغلاق الصفقات وخدمة العملاء.

4️⃣ نصيحة سهيل الاستراتيجية:
ابدئي بعرض إطلاق حصري لأول 50 عميل مع التركيز على القيمة المضافة وليس السعر فقط.`;
    } else if (agent === 'designer') {
      result = `🎨 التوجيه البصري والهوية - ${brand}

1️⃣ لوحة الألوان المقترحة (Color Palette):
- اللون الأساسي: أسود فاحم أو كحلي داكن (للفخامة والثقة).
- اللون الثانوي: ذهبي دافئ أو عنبري (لجذب الانتباه في أزرار الشراء).
- الخلفية: درجات الرمادي الفاتح أو الأبيض المريح للعين.

2️⃣ أفكار تصاميم البوستات (3 قوالب جاهزة):
- بوست 1 (تعريفي): صورة عالية الجودة للمنتج مع جملة خطافية قصيرة في الأعلى.
- بوست 2 (مقارنة): تصميم "قبل وبعد" أو "ليش تختار ${brand}؟".
- بوست 3 (تفاعلي): سؤال للجمهور (${audience}) في الستوري مع استبيان.

3️⃣ نوع الخطوط:
استخدمي خطوط عربية هندسية حديثة مثل (IBM Plex Sans Arabic) أو (Tajawal).`;
    } else if (agent === 'ads') {
      result = `📢 نصوص الحملات الإعلانية الممولة - ${brand}

👻 إعلان سناب شات (مباشر وسريع):
"تدور على الأفضل في ${niche}؟ ${brand} جاب لك الحل اللي يختصر عليك الوقت والجهد! اطلب الحين واستفد من العرض لفترة محدودة 👇 [ارفع الشاشة]"

🎵 إعلان تيك توك (أسلوب عفوي):
"كل ${audience} لازم يجربون ${brand}.. والسبب في الجودة اللي تفرق من أول مرة! الرابط في البايو لا يفوتك."

📸 إعلان إنستغرام (احترافي):
"ارتقِ بتجربتك مع ${brand}. صُمم خصيصاً لـ ${audience} بنبرة ${tone}. اطلب الآن والتوصيل لباب بيتك."

🎯 الـ CTA المقترح: "اطلب الآن" / "تواصل معنا واتساب".`;
    } else if (agent === 'video') {
      result = `🎬 سيناريو ريلز / تيك توك (30 ثانية) - ${brand}

⏱️ (0:00 - 0:03) الخطاف (Hook):
- المشهد: لقطة قريبة جداً للمنتج مع حركة سريعة.
- الصوت: "أكبر غلطة يطيحون فيها ${audience} لما يختارون في مجال ${niche}..."

⏱️ (0:03 - 0:15) المشكلة والحل:
- المشهد: انتقال سلس (Transition) لعرض منتج ${brand} وهو يُستخدم بواقعية.
- النص على الشاشة: "الحل صار بين يديك مع ${brand}".

⏱️ (0:15 - 0:25) الميزة التنافسية:
- المشهد: إظهار تفاصيل الجودة والتغليف أو النتيجة النهائية.
- الصوت: شرح سريع بنبرة ${tone}.

⏱️ (0:25 - 0:30) الخاتمة (CTA):
- المشهد: شعار ${brand} مع سهم يشير للرابط.
- الصوت: "اطلب الحين من الرابط في البايو قبل نفاذ الكمية!"`;
    }

    return NextResponse.json({ result });
  } catch (error) {
    return NextResponse.json({ error: 'حدث خطأ أثناء توليد المحتوى' }, { status: 500 });
  }
}
